#!/usr/bin/env python3

from __future__ import annotations

import re
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parent.parent
PROTO_PATH = REPO_ROOT / "schemas" / "v1" / "monarchic_agent_protocol.proto"
OUTPUT_PATH = (
    REPO_ROOT
    / "formal"
    / "lean"
    / "MonarchicAgentProtocol"
    / "ProtobufSchemaManifest.lean"
)


def extract_symbols(proto_text: str, kind: str) -> list[str]:
    pattern = rf"^{kind}\s+(\w+)\s*\{{"
    return re.findall(pattern, proto_text, re.MULTILINE)


def render_lean_list(symbols: list[str]) -> str:
    if not symbols:
        return "[]"
    lines = [f'  [ "{symbols[0]}"']
    lines.extend(f'  , "{symbol}"' for symbol in symbols[1:])
    lines.append("  ]")
    return "\n".join(lines)


def main() -> None:
    proto_text = PROTO_PATH.read_text()
    messages = extract_symbols(proto_text, "message")
    enums = extract_symbols(proto_text, "enum")

    rendered = f"""import MonarchicAgentProtocol.Protobuf

namespace MonarchicAgentProtocol

abbrev ProtoSchemaSymbolName := String

/- This file is generated by `scripts/generate-lean-protobuf-schema-manifest.py`. -/

def schemaProtoMessages : List ProtoSchemaSymbolName :=
{render_lean_list(messages)}

def schemaProtoEnums : List ProtoSchemaSymbolName :=
{render_lean_list(enums)}

def protoMessageCountFromSchema : Nat := schemaProtoMessages.length

def protoEnumCountFromSchema : Nat := schemaProtoEnums.length

end MonarchicAgentProtocol
"""
    OUTPUT_PATH.write_text(rendered)


if __name__ == "__main__":
    main()
